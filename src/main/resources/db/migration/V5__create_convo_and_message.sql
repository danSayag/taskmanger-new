CREATE TABLE convo(
    convo_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE message(
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_id BIGINT NOT NULL REFERENCES users(id),
    getter_id  BIGINT NOT NULL REFERENCES users(id),
    content    VARCHAR(2000) NOT NULL,
    convo_id   BIGINT REFERENCES convo(convo_id)
);
